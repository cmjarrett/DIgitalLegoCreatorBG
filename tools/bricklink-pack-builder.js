/*
 * BrickLink pack builder
 * ----------------------
 * Turns small official LEGO sets into a themed pack file for the game (packs/<id>.js).
 *
 * BrickLink blocks scripted downloads, so this runs in your own browser:
 *   1. Open https://www.bricklink.com/ (any page) and open the developer console (F12).
 *   2. Paste this whole file into the console and press Enter.
 *   3. Run, for example:
 *        copy(await buildPack({
 *          id: 'dinosaurs', name: 'Dinosaurs', emoji: '🦖',
 *          sets: [
 *            {name: 'Brick Dinos', models: ['7604-1', '7219-1', '40247-1', '7798-1']},
 *          ],
 *        }))
 *   4. The pack file is now on your clipboard: save it as packs/dinosaurs.js and add
 *      <script src="packs/dinosaurs.js"></script> to index.html.
 *
 * Tips: every card set needs exactly 4 models. Sets of about 10–45 pieces play best.
 * A model can be given as '7604-1' (name taken from BrickLink) or ['7604-1', 'Triceratops'].
 */
async function buildPack({id, name, emoji = '🧱', sets}) {
  const parts = {};
  const cleanName = n => n
    .replace(/^Monthly Mini Model Build Set - \d{4} \d\d \w+, /, '')
    .replace(/\s+/g, ' ')
    .replace(/^Advent Calendar \d{4}(?:, [^(]+)? \(Day \d+\) - /, '')
    .replace(/^(?:Sabah|Danone|Kellogg's|Japan) (?:Promotional Set: )?/, '')
    .replace(/ (?:polybag|foil pack|paper bag|blister pack|\{[^}]*\})(?: \/ (?:foil pack|paper bag))?$/i, '')
    .replace(/ - .* Promotional$/, '')
    .replace(/ (?:polybag|foil pack|paper bag)$/i, '')
    .trim();

  async function inventory(setNo) {
    const html = await (await fetch(`https://www.bricklink.com/catalogItemInv.asp?S=${setNo}`)).text();
    const doc = new DOMParser().parseFromString(html, 'text/html');
    const title = (html.match(/<CENTER><FONT[^>]*><B>([^<]+)<\/B>/i) || [])[1] || setNo;
    const items = [];
    let section = '';
    for (const row of doc.querySelectorAll('tr')) {
      const text = row.textContent.replace(/\s+/g, ' ').trim();
      if (/^(Regular|Extra|Alternate)\w* Items:?/.test(text) || /^Counterparts:?/.test(text)) { section = text; continue; }
      if (!row.classList.contains('IV_ITEM') || !/Regular/.test(section)) continue;
      const no = [...row.classList].find(c => c.startsWith('IV_') && c !== 'IV_ITEM').slice(3);
      const cells = text.includes("text('!')") ? text.split("text('!')").pop() : text.replace(/^\*\s*/, '');
      const m = cells.match(/^\s*(\d+)\s*(.*?)\s*Catalog: (Parts|Minifigures): (.*)$/);
      if (!m || /Sticker|Instruction/i.test(m[4])) continue;
      let desc = m[2];
      if (desc.startsWith(no)) desc = desc.slice(no.length);
      desc = desc.replace(/^\s*\(Inv\)/, '').trim();
      let key;
      if (m[3] === 'Minifigures') key = `${no}@m`;
      else {
        const img = (row.querySelector('img') || {}).src || '';
        key = `${no}@${(img.match(/\/P\/(\d+)\//) || [])[1] || 0}`;
      }
      parts[key] = [desc, m[4]];
      const prev = items.find(([k]) => k === key);
      if (prev) prev[1] += +m[1]; else items.push([key, +m[1]]);
    }
    if (!items.length) throw new Error(`No inventory found for ${setNo}`);
    return {title: cleanName(new DOMParser().parseFromString(title, 'text/html').body.textContent), items};
  }

  const out = [];
  for (const s of sets) {
    if (s.models.length !== 4) throw new Error(`"${s.name}" needs exactly 4 models`);
    const models = [];
    for (const entry of s.models) {
      const [no, given] = Array.isArray(entry) ? entry : [entry];
      const inv = await inventory(no);
      models.push({no, name: given || inv.title, p: inv.items});
      console.log(`${no}: ${given || inv.title} (${inv.items.reduce((a, [, q]) => a + q, 0)} pieces)`);
    }
    out.push({id: s.id || s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), name: s.name, models});
  }

  const q = JSON.stringify;
  const partLines = Object.keys(parts).sort().map(k => `    ${q(k)}: ${q(parts[k])},`).join('\n');
  const setLines = out.map(s => `    {id: ${q(s.id)}, name: ${q(s.name)}, models: [\n` +
    s.models.map(m => `      {no: ${q(m.no)}, name: ${q(m.name)}, p: ${q(m.p)}},`).join('\n') + `\n    ]},`).join('\n');
  return `// ${emoji} ${name} pack. Generated by tools/bricklink-pack-builder.js from BrickLink set inventories.
// Part key = "<BrickLink part number>@<BrickLink color id>" ("@m" = minifigure). Models list [partKey, quantity].
registerPack({
  id: ${q(id)}, name: ${q(name)}, emoji: ${q(emoji)},
  parts: {
${partLines}
  },
  sets: [
${setLines}
  ],
});
`;
}
